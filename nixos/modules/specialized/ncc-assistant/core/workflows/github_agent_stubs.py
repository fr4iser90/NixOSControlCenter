"""Deterministic docs stubs for GitHub Agent act-safe ticks.

Callers: ``core.workflows.github_agent_act.apply_item``. LLM catalog creators
(``agents-md-creator`` etc.) remain for rich rewrites — they are not libraries
and do not close gaps unattended. This module writes minimal missing files only
(AGENTS.md, doc/impressum.md, doc/privacy.md, .agents/skills/…/SKILL.md).

User: "damit er autonom erstmal alles macht" / multi-day act-safe docs class.
"""

from __future__ import annotations

from pathlib import Path
from typing import Any


def _write_new(path: Path, body: str) -> dict[str, Any]:
    if path.is_file():
        return {"ok": True, "path": str(path), "created": False, "reason": "exists"}
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(body, encoding="utf-8")
    return {"ok": True, "path": str(path), "created": True, "reason": "created"}


def apply_agents_md_stub(root: Path, *, workspace_id: str) -> dict[str, Any]:
    path = root / "AGENTS.md"
    body = (
        f"# AGENTS — {workspace_id}\n\n"
        "Tool-agnostic entry for coding agents.\n\n"
        "## Hard laws\n\n"
        "1. Prefer existing project docs and tests over inventing process.\n"
        "2. Do not commit secrets or live host paths.\n"
        "3. Ask before destructive git (force push, hard reset).\n\n"
        "## Layout\n\n"
        "Describe the repo layout here as the project grows.\n\n"
        "<!-- stub: ncc-assistant github-agent act-safe -->\n"
    )
    return _write_new(path, body)


