def apply_skills_stub(root: Path, *, workspace_id: str) -> dict[str, Any]:
    skill_dir = root / ".agents" / "skills" / "project-overview"
    path = skill_dir / "SKILL.md"
    if path.is_file():
        return {"ok": True, "path": str(path), "created": False, "reason": "exists"}
    body = (
        f"---\nname: project-overview\ndescription: >-\n"
        f"  Brief orientation for agents working in {workspace_id}.\n---\n\n"
        f"# Project overview — {workspace_id}\n\n"
        "Replace this stub with project-specific agent guidance.\n\n"
        "<!-- stub: ncc-assistant github-agent act-safe -->\n"
    )
    return _write_new(path, body)


APPLIERS = {
    "agents-md": apply_agents_md_stub,
    "impressum": apply_impressum_stub,
    "privacy": apply_privacy_stub,
    "skills": apply_skills_stub,
}


def apply_gap_stub(root: Path, gap_id: str, *, workspace_id: str) -> dict[str, Any]:
    fn = APPLIERS.get(str(gap_id or "").strip())
    if fn is None:
        return {"ok": False, "reason": "no_stub", "path": None, "created": False}
    return fn(root, workspace_id=workspace_id)
